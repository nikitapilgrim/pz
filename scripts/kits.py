#!/usr/bin/env python3
"""Starting kits: config/kits/<name>.txt -> data for the server script (pz_kits.lua) or for the manual pz-kit.

  kits.py lua <kits dir>       print the Lua data file with every kit (pz-init writes it into the game's Lua)
  kits.py resolve <kit file>   print "<Module.ItemId> <count>" lines with one random option per pick group (kit.sh)

Kit file format (comments start with #; Windows line endings and a UTF-8 BOM are fine):
  <Module.ItemId> [count]                                   always given
  pick <group>: <Module.ItemId> [count], <Module.ItemId> [count], ...
      one line per option. One option per group is chosen at random. The first item of an option is its main item
      (the weapon): the server script only picks options whose main item exists in the game, so a weapon from a
      disabled mod never leaves a player with magazines and no gun.
Bad lines are skipped with a warning on stderr; the rest of the kit still works.
"""
import random
import re
import sys
from pathlib import Path

ITEM_RE = re.compile(r"^[A-Za-z0-9_-]+\.[A-Za-z0-9_.-]+$")  # Module.ItemId (PNV ids contain '-')
NAME_RE = re.compile(r"^[a-z0-9_]+$")
PICK_RE = re.compile(r"^pick\s+([^:]+):(.*)$", re.IGNORECASE)
MAX_COUNT = 100


def warn(msg):
    print(f"[kits] WARNING: {msg}", file=sys.stderr)


def parse_entry(text, where):
    parts = text.split()
    if not parts:
        return None
    item = parts[0]
    if not ITEM_RE.match(item):
        warn(f"{where}: '{item}' is not a Module.ItemId, skipped")
        return None
    count = 1
    if len(parts) > 1:
        if parts[1].isdigit() and int(parts[1]) > 0:
            count = min(int(parts[1]), MAX_COUNT)
        else:
            warn(f"{where}: bad count '{parts[1]}' for {item}, using 1")
    if len(parts) > 2:
        warn(f"{where}: text after '{item} {parts[1]}' ignored")
    return item, count


def parse(path):
    """Return (fixed entries, {group: [option entries, ...]}) for one kit file."""
    path = Path(path)
    fixed, groups = [], {}
    text = path.read_text(encoding="utf-8-sig", errors="replace")
    for number, raw in enumerate(text.splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        where = f"{path.name}:{number}"
        pick = PICK_RE.match(line)
        if pick:
            group = pick.group(1).strip().lower()
            if not NAME_RE.match(group):
                warn(f"{where}: group name '{group}' must be letters, digits or _, line skipped")
                continue
            option = [e for e in (parse_entry(t, where) for t in pick.group(2).split(",")) if e]
            if option:
                groups.setdefault(group, []).append(option)
            else:
                warn(f"{where}: pick option without items, skipped")
            continue
        entry = parse_entry(line, where)
        if entry:
            fixed.append(entry)
    return fixed, groups


def lua_entries(entries):
    return ", ".join(f'{{ "{item}", {count} }}' for item, count in entries)


def to_lua(kits_dir):
    out = [
        "-- Generated by pz-init from config/kits/*.txt on every start. Edit config/kits, not this file.",
        "PZViewpointKits = {}",
    ]
    for path in sorted(Path(kits_dir).glob("*.txt")):
        name = path.stem.lower()
        if not NAME_RE.match(name):
            warn(f"{path.name}: kit file names must be letters, digits or _ (the profession part), skipped")
            continue
        try:
            fixed, groups = parse(path)
        except OSError as exc:
            warn(f"{path.name}: cannot read ({exc}), skipped")
            continue
        out.append(f'PZViewpointKits["{name}"] = {{')
        out.extend(f'  {{ "{item}", {count} }},' for item, count in fixed)
        if groups:
            out.append("  pick = {")
            for group in sorted(groups):
                out.append(f'    ["{group}"] = {{')
                out.extend(f"      {{ {lua_entries(option)} }}," for option in groups[group])
                out.append("    },")
            out.append("  },")
        out.append("}")
    return "\n".join(out) + "\n"


def resolve(path, rng=random):
    fixed, groups = parse(path)
    lines = [f"{item} {count}" for item, count in fixed]
    for group in sorted(groups):
        lines.extend(f"{item} {count}" for item, count in rng.choice(groups[group]))
    return lines


def main(argv):
    if len(argv) == 3 and argv[1] == "lua":
        sys.stdout.write(to_lua(argv[2]))
        return 0
    if len(argv) == 3 and argv[1] == "resolve":
        print("\n".join(resolve(argv[2])))
        return 0
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
