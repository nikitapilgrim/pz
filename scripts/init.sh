#!/usr/bin/env bash
# pz-init: one-shot preparation, runs as root before every server start (docker compose does it).
#   1. data volumes owned by the server user 10000:10000
#   2. passwords generated once, stored in the pz-data volume, printed to this log
#   3. configs from config/ applied on every start (the repo is the source of truth)
#   4. memory sanity check
#   5. missing Workshop mods downloaded with SteamCMD (much faster than the server's own downloader)
# Print the passwords again: docker compose run --rm pz-init passwords
set -euo pipefail

FILES=/home/steam/zomboid
DATA=/home/steam/zomboid_data
TEMPLATES=/pz/config
SECRETS="$DATA/.pz-secrets.env"
PZ_UID=10000
PZ_GID=10000
SERVER_NAME="${SERVER_NAME:-PZViewpoint}"

log()  { printf '[pz-init] %s\n' "$*"; }
warn() { printf '[pz-init] WARNING: %s\n' "$*"; }

# Value set in .env wins; otherwise the generated one from the data volume.
secret() {
  local key="$1" val="${!1:-}"
  if [ -z "$val" ] && [ -f "$SECRETS" ]; then
    val="$(grep -E "^${key}=" "$SECRETS" | tail -n 1 | cut -d= -f2-)"
  fi
  printf '%s' "$val"
}

print_passwords() {
  log "=================================================================="
  log " Server password (give it to friends): $(secret SERVER_PASSWORD)"
  log " Admin login: ${ADMIN_USERNAME:-admin}   admin password: $(secret ADMIN_PASSWORD)"
  log "=================================================================="
}

if [ "${1:-}" = "passwords" ]; then
  print_passwords
  exit 0
fi

# 0. Server-side Lua in the game's own media/lua/server (players install nothing):
#    automatic kits: config/kits/<name>.txt -> a character whose profession contains <name> gets that kit once
#    (scripts/pz_kits.lua); helicopter flyovers every ~HELI_FLYOVER_DAYS in-game days (scripts/pz_heli.lua).
KITS_DIR=/pz/kits
LUA_DIR="$FILES/media/lua/server/PZViewpoint"
mkdir -p "$LUA_DIR"
if [ "${AUTO_KITS:-true}" = "true" ] && python3 /pz/scripts/kits.py lua "$KITS_DIR" > "$LUA_DIR/00_PZViewpointKitsData.lua"; then
  sed 's/\r$//' /pz/scripts/pz_kits.lua > "$LUA_DIR/10_PZViewpointKits.lua"
  log "automatic kits: $(cd "$KITS_DIR" && ls -1 *.txt 2> /dev/null | sed 's/\.txt$//' | tr '\n' ' ')"
else
  [ "${AUTO_KITS:-true}" = "true" ] && warn "config/kits could not be read (see above): automatic kits are off"
  rm -f "$LUA_DIR/00_PZViewpointKitsData.lua" "$LUA_DIR/10_PZViewpointKits.lua"
fi
heli_days="$(awk -v v="${HELI_FLYOVER_DAYS:-0}" 'BEGIN { n = v + 0; if (n < 0) n = 0; printf "%g", n }')"
if [ "$heli_days" != "0" ]; then
  {
    echo "-- Generated by pz-init from HELI_FLYOVER_DAYS on every start. Edit .env, not this file."
    echo "PZViewpointHeli = { flyoverDays = $heli_days }"
  } > "$LUA_DIR/05_PZViewpointHeliData.lua"
  sed 's/\r$//' /pz/scripts/pz_heli.lua > "$LUA_DIR/20_PZViewpointHeli.lua"
  log "helicopter flyovers: every ~${heli_days} game days"
else
  rm -f "$LUA_DIR/05_PZViewpointHeliData.lua" "$LUA_DIR/20_PZViewpointHeli.lua"
fi
# Whole map known in multiplayer (scripts/pz_map.lua); it follows Map.MapAllKnown in config/SandboxVars.lua.
sed 's/\r$//' /pz/scripts/pz_map.lua > "$LUA_DIR/30_PZViewpointMap.lua"

# 1. Ownership: the image runs the server as 10000:10000; new Docker volumes start out owned by root.
mkdir -p "$DATA/Server"
for d in "$FILES" "$DATA"; do
  find "$d" -xdev \( ! -user "$PZ_UID" -o ! -group "$PZ_GID" \) -exec chown -h "$PZ_UID:$PZ_GID" {} +
done
log "volumes owned by $PZ_UID:$PZ_GID"

# 2. Passwords: generated on the first start only.
gen() { head -c 48 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | cut -c 1-16; }
if [ ! -f "$SECRETS" ]; then
  (
    umask 077
    {
      echo "# Generated by pz-init on the first start. Values set in .env take precedence."
      echo "SERVER_PASSWORD=$(gen)"
      echo "ADMIN_PASSWORD=$(gen)"
      echo "RCON_PASSWORD=$(gen)"
    } > "$SECRETS"
  )
  chown "$PZ_UID:$PZ_GID" "$SECRETS"
  log "generated passwords (kept in the pz-data volume)"
fi

# 3. Configs. The server reads them at start, so changes in config/ reach an existing world after a restart.
#    Sandbox options changed in-game are overwritten here: change config/SandboxVars.lua instead.
#    (Some sandbox rules - start date, water/power shutoff day, zombie distribution - only matter for a new world.)
install_cfg() {
  local src="$TEMPLATES/$1" dst="$DATA/Server/${SERVER_NAME}$2" new
  new="$(mktemp)"
  sed 's/\r$//' "$src" > "$new"
  if ! cmp -s "$new" "$dst" 2> /dev/null; then
    install -m 644 -o "$PZ_UID" -g "$PZ_GID" "$new" "$dst"
    log "updated Server/${SERVER_NAME}$2 from config/$1"
  fi
  rm -f "$new"
}
install_cfg SandboxVars.lua _SandboxVars.lua
install_cfg spawnregions.lua _spawnregions.lua
# Bandits mod overrides (config/bandits/*.txt): the mod loads Lua/bandits/ of the server after its own files.
mkdir -p "$DATA/Lua/bandits"
chown "$PZ_UID:$PZ_GID" "$DATA/Lua" "$DATA/Lua/bandits"
for f in "$TEMPLATES"/bandits/*.txt; do
  [ -f "$f" ] || continue
  sed 's/\r$//' "$f" > "$DATA/Lua/bandits/$(basename "$f")"
  chown "$PZ_UID:$PZ_GID" "$DATA/Lua/bandits/$(basename "$f")"
done
if [ ! -f "$DATA/Server/${SERVER_NAME}.ini" ]; then
  sed 's/\r$//' "$TEMPLATES/server.ini" > "$DATA/Server/${SERVER_NAME}.ini"
  chown "$PZ_UID:$PZ_GID" "$DATA/Server/${SERVER_NAME}.ini"
  log "seeded Server/${SERVER_NAME}.ini"
fi

# config/server.ini is the source of truth for its keys: applied on every start. Keys the image sets
# from env on every start are skipped (change those in .env).
managed='^(SaveWorldEveryMinutes|BackupsCount|BackupsPeriod|UDPPort|DefaultPort|Map|MaxPlayers|PauseEmpty|PingLimit|PVP|Public|PublicName|SteamVAC|AntiCheatProtectionType21|WorkshopItems|Mods|RCONPassword|RCONPort|Password)$'
live="$DATA/Server/${SERVER_NAME}.ini"
applied=0
while IFS= read -r line || [ -n "$line" ]; do
  line="${line%$'\r'}"
  case "$line" in ''|'#'*) continue ;; esac
  key="${line%%=*}"
  [[ "$key" =~ $managed ]] && continue
  python3 /home/steam/config_editor.py --config "$live" --key "$key" --value "${line#*=}" > /dev/null
  applied=$((applied + 1))
done < "$TEMPLATES/server.ini"
chown "$PZ_UID:$PZ_GID" "$live"
log "applied $applied settings from config/server.ini"

# 4. Memory: the JVM heap plus ~1 GB must fit into what Docker has (Docker Desktop gets half the RAM by default).
heap_mb="$(awk -v v="${MAX_MEMORY:-0}" 'BEGIN { n = v + 0; u = tolower(substr(v, length(v))); if (u == "g") n *= 1024; print int(n) }')"
total_mb="$(awk '/^MemTotal:/ { print int($2 / 1024) }' /proc/meminfo 2> /dev/null || true)"
total_mb="${total_mb:-0}"
if [ "$heap_mb" -gt 0 ] && [ "$total_mb" -gt 0 ] && [ $((heap_mb + 1024)) -gt "$total_mb" ]; then
  warn "MAX_MEMORY=${MAX_MEMORY} needs ~$((heap_mb + 1024)) MB, but Docker only has ${total_mb} MB."
  warn "Lower MAX_MEMORY in .env (see .env.example) or give Docker more memory."
fi

# 5. Workshop mods: download only the missing ones.
if [ "${PZ_SKIP_MOD_DOWNLOAD:-false}" = "true" ]; then
  log "mod download skipped (PZ_SKIP_MOD_DOWNLOAD=true)"
else
  IFS=';' read -r -a ids <<< "${MOD_IDS:-}"
  missing=()
  for id in "${ids[@]}"; do
    if [ -n "$id" ] && [ ! -d "$FILES/steamapps/workshop/content/108600/$id" ]; then missing+=("$id"); fi
  done
  if [ "${#missing[@]}" -eq 0 ]; then
    log "all ${#ids[@]} Workshop items are present"
  else
    log "downloading ${#missing[@]} Workshop items with SteamCMD (first start takes a few minutes)..."
    args=()
    for id in "${missing[@]}"; do args+=(+workshop_download_item 108600 "$id"); done
    runuser -u steam -- env HOME=/home/steam /home/steam/steamcmd/steamcmd.sh \
      +force_install_dir "$FILES" +login anonymous "${args[@]}" +quit \
      | grep -aE 'Success\. Downloaded|ERROR|Failed' || true
    still=()
    for id in "${missing[@]}"; do
      [ -d "$FILES/steamapps/workshop/content/108600/$id" ] || still+=("$id")
    done
    if [ "${#still[@]}" -gt 0 ]; then
      warn "not downloaded: ${still[*]} - the server will try to fetch them itself (slowly)"
    else
      log "Workshop items downloaded"
    fi
  fi
fi

print_passwords
log "ready - starting the server (watch it with: docker compose logs -f pz-server)"
